/** AppIcon 的全局默认值，可由 configureIconDefaults 或 createUi 的 iconDefaults 覆盖 */
const iconDefaults = reactive({
    strokeWidth: 1.8,
    spring: { stiffness: 520, damping: 34 },
    speed: 1,
    reducedMotion: 'user',
})

export function configureIconDefaults(options = {}) {
    for (const key of ['strokeWidth', 'spring', 'speed', 'reducedMotion']) {
        if (options[key] !== undefined) iconDefaults[key] = options[key]
    }
}

export function getIconDefaults() {
    return iconDefaults
}

export function configureIcons(icons = {}) {
    for (const [name, value] of Object.entries(icons || {})) {
        if (value === null || value === undefined) delete registry[name]
        else registry[name] = value
    }
}

export function getIcon(name) {
    return registry[name]
}

export function iconNames() {
    return Object.keys(registry)
}
